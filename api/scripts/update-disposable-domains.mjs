#!/usr/bin/env node
/**
 * Regenerate src/lib/disposableDomains.ts from the maintained open blocklist
 * (https://github.com/disposable-email-domains/disposable-email-domains, CC0)
 * plus the domains below that we have seen abuse signups but that the list
 * does not (yet) carry. Run from api/:  node scripts/update-disposable-domains.mjs
 */
import { writeFileSync } from "node:fs";

const SOURCE = "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";

// Seen on ArchTools, not in the upstream list. 2026-11-02: 35 + 25 accounts created
// on 2026-10-14 from these two domains, none ever verified (credit-farming wave).
const LOCAL_EXTRA = ["nexotp.web.id", "trialkupremium.web.id"];

// The hand-maintained list that verification.ts carried before this file existed.
const PREVIOUS_LIST = [
  "mailinator.com", "guerrillamail.com", "guerrillamail.net", "sharklasers.com",
  "10minutemail.com", "10minutemail.net", "temp-mail.org", "tempmail.com",
  "tempmail.dev", "tempmailo.com", "throwawaymail.com", "yopmail.com",
  "yopmail.net", "getnada.com", "nada.email", "maildrop.cc", "mailnesia.com",
  "trashmail.com", "trashmail.de", "dispostable.com", "fakeinbox.com",
  "mintemail.com", "mohmal.com", "mytemp.email", "tempinbox.com",
  "spamgourmet.com", "mailcatch.com", "inboxkitten.com", "emailondeck.com",
  "burnermail.io", "33mail.com", "spambox.us", "mailsac.com", "tmpmail.org",
  "tmpmail.net", "tmail.ws", "moakt.com", "tempr.email", "discard.email",
  "mail-temp.com", "luxusmail.org", "instaddr.ch", "anonbox.net",
];

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`blocklist fetch failed: ${res.status}`);
const upstream = (await res.text())
  .split("\n")
  .map((l) => l.trim().toLowerCase())
  .filter((l) => l && !l.startsWith("#"));
if (upstream.length < 1000) throw new Error(`blocklist suspiciously short: ${upstream.length}`);

const domains = [...new Set([...upstream, ...PREVIOUS_LIST, ...LOCAL_EXTRA])].sort();
const out = `// GENERATED by scripts/update-disposable-domains.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.
// Source: ${SOURCE} (CC0) + local additions (see the script).
// ${domains.length} domains.
export const DISPOSABLE_DOMAINS: ReadonlySet<string> = new Set([
${domains.map((d) => `  ${JSON.stringify(d)},`).join("\n")}
]);
`;
writeFileSync(new URL("../src/lib/disposableDomains.ts", import.meta.url), out);
console.log(`wrote ${domains.length} domains (${upstream.length} upstream)`);
